import AppKit
import Combine

nonisolated struct ClipItem: Identifiable, Equatable, Codable, Sendable {
    let id: UUID
    let text: String
    let kind: ClipKind
    let date: Date
    /// Name given by the user, e.g. "DB password". A labeled item shows the
    /// label and hides its value.
    var label: String?

    init(id: UUID = UUID(), text: String, kind: ClipKind? = nil, date: Date = .now, label: String? = nil) {
        self.id = id
        self.text = text
        self.kind = kind ?? DevToolkit.kind(of: text)
        self.date = date
        self.label = label
    }

    var isLabeled: Bool { label != nil }

    /// First line, trimmed, for the list.
    var preview: String {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let firstLine = trimmed.split(separator: "\n", maxSplits: 1).first.map(String.init) ?? trimmed
        return String(firstLine.prefix(200))
    }
}

/// Text copied recently, kept in memory only and never written to disk.
/// Items that password managers mark as concealed are skipped. Pinned items
/// are the exception: they're saved in the Keychain so they survive a restart.
final class ClipboardService: ObservableObject {
    /// Recent copies, newest first. Memory only.
    @Published private(set) var items: [ClipItem] = []
    /// Pinned snippets, in the order they were pinned. Saved in the Keychain.
    @Published private(set) var pinned: [ClipItem] = []
    /// Text on the clipboard right now (nil for concealed or non-text
    /// copies). The Tools and Hash views work on this.
    @Published private(set) var current: String?

    static let maxItems = 25
    /// Copies bigger than this are skipped; they aren't snippets.
    static let maxLength = 100_000

    private let pasteboard: NSPasteboard
    private let pinnedStore: PinnedClipStore
    private var lastChangeCount: Int
    private var pollTask: Task<Void, Never>?
    /// Change count of our own writes, so copying an item back doesn't duplicate it.
    private var ownChangeCount: Int?

    private static let ignoredTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    init(pasteboard: NSPasteboard = .general, pinnedStore: PinnedClipStore = KeychainPinnedClipStore()) {
        self.pasteboard = pasteboard
        self.pinnedStore = pinnedStore
        lastChangeCount = pasteboard.changeCount
        current = readText()
        loadPinned()
    }

    var historyEnabled: Bool {
        UserDefaults.standard.bool(forKey: SettingsKeys.featureDev)
            && UserDefaults.standard.bool(forKey: SettingsKeys.clipboardHistory)
    }

    func start() {
        guard pollTask == nil else { return }
        pollTask = Task { [weak self] in
            while !Task.isCancelled {
                self?.check()
                try? await Task.sleep(for: .milliseconds(800))
            }
        }
    }

    /// Copies an item's value. Labeled items are marked concealed so other
    /// clipboard managers don't record secrets.
    func copy(_ item: ClipItem) {
        copy(item.text, concealed: item.isLabeled)
    }

    func copy(_ text: String, concealed: Bool = false) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        if concealed {
            pasteboard.setString("", forType: .init("org.nspasteboard.ConcealedType"))
        }
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
        current = text
        // Pinned items stay where they are.
        if pinned.contains(where: { $0.text == text }) { return }
        // Move it to the top without adding a duplicate.
        if let index = items.firstIndex(where: { $0.text == text }) {
            let item = items.remove(at: index)
            items.insert(item, at: 0)
        } else if historyEnabled {
            insert(text)
        }
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        if pinned.contains(where: { $0.id == item.id }) {
            pinned.removeAll { $0.id == item.id }
            savePinned()
        }
    }

    /// Clears the history; pinned items stay.
    func clear() {
        items.removeAll()
    }

    func isPinned(_ item: ClipItem) -> Bool {
        pinned.contains { $0.id == item.id }
    }

    func pin(_ item: ClipItem) {
        guard !isPinned(item) else { return }
        items.removeAll { $0.id == item.id || $0.text == item.text }
        pinned.append(item)
        savePinned()
    }

    /// Back to the top of the history, label and all. Unpinned items live in
    /// memory only, so they're gone after a restart.
    func unpin(_ item: ClipItem) {
        guard let index = pinned.firstIndex(where: { $0.id == item.id }) else { return }
        let current = pinned.remove(at: index)
        savePinned()
        items.insert(current, at: 0)
        trimHistory()
    }

    /// Names an item. The first label on a history item pins it so it's
    /// kept; renaming or clearing a label leaves it where it is.
    func setLabel(_ label: String, for item: ClipItem) {
        let trimmed = label.trimmingCharacters(in: .whitespacesAndNewlines)
        let newLabel = trimmed.isEmpty ? nil : String(trimmed.prefix(60))
        if let index = pinned.firstIndex(where: { $0.id == item.id }) {
            pinned[index].label = newLabel
            savePinned()
        } else if let index = items.firstIndex(where: { $0.id == item.id }) {
            if items[index].label == nil, newLabel != nil {
                var updated = items[index]
                updated.label = newLabel
                pin(updated)
            } else {
                items[index].label = newLabel
            }
        }
    }

    func togglePin(_ item: ClipItem) {
        isPinned(item) ? unpin(item) : pin(item)
    }


    private func check() {
        guard UserDefaults.standard.bool(forKey: SettingsKeys.featureDev) else { return }
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        let text = readText()
        current = text
        guard historyEnabled else {
            if !items.isEmpty { items.removeAll() }
            return
        }
        guard count != ownChangeCount, let text else { return }
        insert(text)
    }

    /// Plain text on the clipboard, unless it's concealed, empty or huge.
    private func readText() -> String? {
        let types = pasteboard.types ?? []
        guard !types.contains(where: Self.ignoredTypes.contains),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.count <= Self.maxLength
        else { return nil }
        return text
    }

    /// Adds a copy to the history. Internal for tests.
    func insert(_ text: String) {
        // Already pinned: no need to list it twice.
        guard !pinned.contains(where: { $0.text == text }) else { return }
        // Copied again: move it up and keep its label.
        if let index = items.firstIndex(where: { $0.text == text }) {
            items.insert(items.remove(at: index), at: 0)
            return
        }
        items.insert(ClipItem(text: text), at: 0)
        trimHistory()
    }

    private func trimHistory() {
        if items.count > Self.maxItems { items.removeLast(items.count - Self.maxItems) }
    }

    // MARK: Pinned storage

    private func loadPinned() {
        guard let data = pinnedStore.load() else { return }
        pinned = (try? JSONDecoder().decode([ClipItem].self, from: data)) ?? []
    }

    private func savePinned() {
        guard let data = try? JSONEncoder().encode(pinned) else { return }
        pinnedStore.save(data)
    }
}
